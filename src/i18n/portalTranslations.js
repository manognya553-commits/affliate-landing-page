export function getPortalCopy(lang = 'en') {
  return lang === 'te' ? portalTe : portalEn
}

export function getPortalText(lang = 'en', path = '') {
  const dict = lang === 'te' ? portalTe : portalEn
  if (!path) return dict
  const parts = path.split('.')
  let current = dict
  for (const part of parts) {
    if (current == null) {
      current = null
      break
    }
    current = current[part]
  }
  if (current != null && current !== dict) return current

  // Fallback: check nested under dict.shell
  if (dict.shell) {
    let shellCurrent = dict.shell
    for (const part of parts) {
      if (shellCurrent == null) {
        shellCurrent = null
        break
      }
      shellCurrent = shellCurrent[part]
    }
    if (shellCurrent != null && shellCurrent !== dict.shell) return shellCurrent
  }

  return path
}
